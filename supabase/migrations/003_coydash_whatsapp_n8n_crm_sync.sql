DO $mig003$
BEGIN

-- 1. Tabela `public.leads` (100% compatível com os nodes Supabase do n8n + metadados CoyDash)
CREATE TABLE IF NOT EXISTS public.leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    lead_nome TEXT NULL,
    lead_id TEXT NOT NULL UNIQUE,
    organization_id UUID NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    client_id UUID NULL REFERENCES public.clients(id) ON DELETE SET NULL,
    crm_stage TEXT NOT NULL DEFAULT 'ONBOARDING',
    avatar_url TEXT NULL,
    human_takeover BOOLEAN NOT NULL DEFAULT false,
    assigned_agent_id TEXT NULL,
    orders_count INTEGER NOT NULL DEFAULT 0,
    total_spent NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    cashback_balance NUMERIC(12,2) NOT NULL DEFAULT 0.00
);

ALTER TABLE public.leads
    ADD COLUMN IF NOT EXISTS organization_id UUID NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    ADD COLUMN IF NOT EXISTS client_id UUID NULL REFERENCES public.clients(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS crm_stage TEXT NOT NULL DEFAULT 'ONBOARDING',
    ADD COLUMN IF NOT EXISTS avatar_url TEXT NULL,
    ADD COLUMN IF NOT EXISTS human_takeover BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS assigned_agent_id TEXT NULL,
    ADD COLUMN IF NOT EXISTS orders_count INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS total_spent NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    ADD COLUMN IF NOT EXISTS cashback_balance NUMERIC(12,2) NOT NULL DEFAULT 0.00;

CREATE INDEX IF NOT EXISTS idx_leads_lead_id ON public.leads(lead_id);
CREATE INDEX IF NOT EXISTS idx_leads_org_id ON public.leads(organization_id);

-- 2. Tabela `public.n8n_chat_histories` (Compatível com Postgres Chat Memory do n8n + hora_data_mensagem)
CREATE TABLE IF NOT EXISTS public.n8n_chat_histories (
    id SERIAL PRIMARY KEY,
    session_id VARCHAR(255) NOT NULL,
    message JSONB NOT NULL,
    hora_data_mensagem TIMESTAMPTZ NOT NULL DEFAULT now(),
    organization_id UUID NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    sender_type TEXT GENERATED ALWAYS AS (COALESCE(message->>'type', 'human')) STORED
);

ALTER TABLE public.n8n_chat_histories
    ADD COLUMN IF NOT EXISTS hora_data_mensagem TIMESTAMPTZ NOT NULL DEFAULT now(),
    ADD COLUMN IF NOT EXISTS organization_id UUID NULL REFERENCES public.organizations(id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_n8n_chat_session_time
    ON public.n8n_chat_histories(session_id, hora_data_mensagem ASC);

-- 3. Tabela `public.client_ai_memories` (Memória Vetorial pgvector por Lead)
CREATE TABLE IF NOT EXISTS public.client_ai_memories (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    organization_id UUID NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    lead_id TEXT NOT NULL,
    memory_text TEXT NOT NULL,
    embedding vector(1536) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_client_ai_memories_lead_id
    ON public.client_ai_memories(lead_id);

-- 4. Colunas extras de Z-API e Agente n8n em `public.organization_settings`
ALTER TABLE public.organization_settings
    ADD COLUMN IF NOT EXISTS zapi_instance_url TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS zapi_client_token TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS n8n_webhook_url TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS agent_builder_config JSONB NOT NULL DEFAULT '{}'::jsonb;

-- 5. RLS e Permissões para `service_role`, `authenticated` e `anon` (para Realtime e n8n)
ALTER TABLE public.leads ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.n8n_chat_histories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.client_ai_memories ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "allow_all_authenticated_leads" ON public.leads;
CREATE POLICY "allow_all_authenticated_leads" ON public.leads
    FOR ALL TO authenticated, service_role
    USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "allow_all_authenticated_n8n_chat" ON public.n8n_chat_histories;
CREATE POLICY "allow_all_authenticated_n8n_chat" ON public.n8n_chat_histories
    FOR ALL TO authenticated, service_role
    USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "allow_all_authenticated_client_memories" ON public.client_ai_memories;
CREATE POLICY "allow_all_authenticated_client_memories" ON public.client_ai_memories
    FOR ALL TO authenticated, service_role
    USING (true) WITH CHECK (true);

GRANT ALL ON public.leads TO postgres, anon, authenticated, service_role;
GRANT ALL ON public.n8n_chat_histories TO postgres, anon, authenticated, service_role;
GRANT ALL ON public.client_ai_memories TO postgres, anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO postgres, anon, authenticated, service_role;

-- 6. Habilitar Supabase Realtime para as 3 tabelas
BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.leads;
EXCEPTION WHEN duplicate_object THEN NULL;
END;

BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.n8n_chat_histories;
EXCEPTION WHEN duplicate_object THEN NULL;
END;

BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.client_ai_memories;
EXCEPTION WHEN duplicate_object THEN NULL;
END;

END
